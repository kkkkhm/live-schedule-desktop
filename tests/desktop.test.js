const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const main = fs.readFileSync(path.join(root, "desktop", "main.js"), "utf8");
const preload = fs.readFileSync(path.join(root, "desktop", "preload.js"), "utf8");
const menu = fs.readFileSync(path.join(root, "desktop", "menu.js"), "utf8");
const macPackager = fs.readFileSync(path.join(root, "desktop", "package-mac.js"), "utf8");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const workflow = fs.readFileSync(path.join(root, ".github", "workflows", "build-desktop.yml"), "utf8");

assert.equal(packageJson.main, "desktop/main.js");
assert.match(packageJson.scripts["pack:win"], /--win portable --x64/);
assert.match(packageJson.scripts["pack:mac"], /package-mac\.js/);
assert.match(macPackager, /"ditto"/);
assert.match(macPackager, /packageArchitecture\("x64", "mac"\)/);
assert.match(macPackager, /packageArchitecture\("arm64", "mac-arm64"\)/);
assert.deepEqual(packageJson.build.files.includes("vendor/**/*"), true);
assert.deepEqual(packageJson.build.files.includes("excel.js"), true);
assert.deepEqual(packageJson.build.files.includes("channel-summary.js"), true);
assert.match(main, /nodeIntegration:\s*false/);
assert.match(main, /contextIsolation:\s*true/);
assert.match(main, /sandbox:\s*true/);
assert.match(main, /autoHideMenuBar:\s*false/);
assert.match(main, /AppMenu\.installApplicationMenu/);
assert.match(main, /setWindowOpenHandler\(\(\) => \(\{ action: "deny" \}\)\)/);
assert.match(main, /will-navigate/);
assert.match(main, /Updates\.isAllowedExternalUrl/);
assert.match(preload, /contextBridge\.exposeInMainWorld\("desktopUpdates"/);
assert.match(preload, /contextBridge\.exposeInMainWorld\("desktopMenu"/);
assert.doesNotMatch(preload, /exposeInMainWorld\("ipcRenderer"/);
assert.doesNotMatch(preload, /require\("node:fs"\)/);
assert.match(menu, /https:\/\/github\.com\/kkkkhm\/live-schedule-desktop#readme/);
assert.match(html, /Content-Security-Policy/);
assert.doesNotMatch(html, /id="checkUpdateBtn"/);
assert.doesNotMatch(html, /id="exportJsonBtn"/);
assert.doesNotMatch(html, /id="exportScheduleXlsxBtn"/);
assert.match(html, /id="scheduleExcelInput"/);
assert.match(html, /id="performanceExcelInput"/);
assert.match(html, /id="channelSummaryExcelInput"/);
assert.match(html, /data-tab="channel-summary"/);
assert.match(html, /id="excelImportDialog"/);
assert.match(html, /id="defaultNormalHoursInput"/);
assert.match(html, /id="maximumOvertimeHoursInput"/);
assert.ok(html.indexOf('src="logic.js"') < html.indexOf('src="excel.js"'));
assert.ok(html.indexOf('src="excel.js"') < html.indexOf('src="app.js"'));
assert.ok(html.indexOf('src="channel-summary.js"') < html.indexOf('src="app.js"'));
assert.match(workflow, /gh release create/);
assert.match(workflow, /GH_REPO: \$\{\{ github\.repository \}\}/);
assert.match(workflow, /needs: build/);
assert.match(workflow, /desktop-dist\/LiveSchedule-Windows-\*\.exe/);
assert.match(workflow, /desktop-dist\/LiveSchedule-macOS-\*\.zip/);

console.log("PASS desktop packaging and security configuration");

